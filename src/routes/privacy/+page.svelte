Last Updated: 11/2/26

Welcome to Violetproject, defined throughout this document as "we," "us," "our," and "Site". This Privacy Policy outlines what information we collect,
the purpose of collecting and usage of information, how we handle and protect it, and the rights You have regarding Your personal data.

For the purposes of this Privacy Policy, the following terms shall have the meanings set forth below.

Terms & Definitions
Throughout this Privacy Policy, when we say "You," "Your," or "User," we refer to any person or legal entity accessing, browsing,
or interacting with the Site in any form, whether as a Guest or as a registered Account holder (defined below).

"Guest" refers to any person or legal entity accessing, browsing, or interacting with the Site in any form without creating or logging into an Account (defined below).

"Game" (or "Games") refers to any browser-based playable game hosted and accessible on the Site.

When we say "Account", this refers to a unique profile created for You, or by You, for You to access, interact with,
or use the Site in any form. An Account may include a username and password, Account sessions, User-Generated Content (herein defined below),
chat history, or settings associated with Your registered profile on the Site. More details about what information an Account includes is defined later in this document.

"User-Generated Content" refers to chat messages or screenshots generated and uploaded by any User of the site.
User-Generated Content may also include Game saves, and settings configured via the browser interface.

1. Information We Collect
A. Account & Authentication Data
When You use the Site as a Guest, we do not collect any information. Gameplay data is only relayed to other Guests or Users of the Site.

When You create an Account on the Site, we may collect the following information

The username you sign up with, used to identify Accounts by name.
The password you sign up with, stored using strong state-of-the-art encryption, hashing and salting algorithms.
Your IP address, used to identify the devices each User signs in from and to facilitate User security.
Device User Agent, used to identify the devices each User signs in from and to facilitate User security.
Session token, stored on the Site to preserve Your active browser Account session.
Site cookie, stored on device to preserve Your active browser Account session.
We do not share any login information, IP addresses, device user agents, session tokens, or cookies with third-parties.

B. User-Generated Content (UGC) & Chat Data
As a registered User of the site, you may choose to submit User-Generated Content to the Site. Such examples of User-Generated Content include:

Chat Messages & Content: The text and content of messages You send on the Site.
Screenshots: Screenshots generated by You, hosted by the Site.
Metadata: Date and time stamps, and Games (where applicable) associated with Your chat messages and screenshots.
2. How We Use Your Data
We do not monetize Your data. We use the collected information strictly for the following internal purposes:

Authentication & Access: Verifying Your identity, maintaining active sessions, and allowing You to access Your Account.
Service Delivery: Displaying Your User-Generated Content, chat messages, and providing You access to the Games on the Site.
Security & Troubleshooting: Monitoring system stability, defending against abuse, preventing unauthorized access, and debugging technical issues.
3. Third-Party Services & Data Transfers
We host the Site on our own in-house server.
We do not use third-party analytics (such as Google Analytics), tracking networks, or external database providers.

The only external services involved with the Site are:

Cloudflare (Security & CDN): We use Cloudflare for DDoS protection, network performance, and automated content scanning
to detect malicious traffic. Data such as Your IP address, User-Agent, and web traffic pass through Cloudflare's global network to reach our server.
Ko-Fi (Donations): If You choose to support us financially, donations are processed through Ko-Fi.
We do not receive, store, or process any payment card details or financial information on our server; all transaction data is handled
directly by Ko-Fi and its supported payment providers (such as PayPal or Stripe).
No Data Sales: We do not sell, rent, trade, or share Your personal information with third parties for marketing or advertising purposes.

4. Data Retention & Deletion Policy
Active Accounts: We retain Your Account details, session data, and User-Generated Content to provide You access to the service.
You may schedule deletion of your Account via the website interface, or by contacting us at privacy@violetproject.net
Deletion Requests & Retention: If You request the deletion of Your Account (via the website interface, email, or our contact form), 
we may retain Your user information for up to two (2) months (60 days) after receiving the request. 
We reserve the right to retain such data to respond to legal obligations before it is permanently deleted.
5. Cookies & Tracking Technologies
We use essential session tokens and cookies necessary for site navigation and security.

Essential Cookies: Required for maintaining Your login session across pages.
Settings Cookies: Used to facilitate providing settings with or without an Account.
You can clear or block cookies through Your browser settings, though doing so may prevent You from staying logged in
or using certain Account features.

6. Children's Privacy
This Site is not intended for use by children under the age of 16. We do not knowingly collect personal information from children, 
including Accounts or User-Generated Content from anyone under 16.

If you are under 16, please do not create an Account, play hosted Games, or provide any personal information on the Site.

If we discover that a Guest or User under the age of 16 has provided us with personal information, we will delete that information 
and terminate the associated Account as quickly as possible.
If a parent or legal guardian believes that their child has provided personal data to us, please contact us immediately at contact@violetproject.net.
Upon verification, we will take prompt steps to remove the child's data from our primary servers and purge it in accordance with our data retention practices.

7. Updates to This Policy
We reserve the right to update this Privacy Policy as the Site evolves. Any changes will be posted on this page with an updated "Last Updated" date above.

8. Contact Us
If You have questions about this policy or wish to submit a data deletion request, You can contact us via:

